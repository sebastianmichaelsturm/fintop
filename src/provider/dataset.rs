#[allow(clippy::too_many_arguments)]
fn stock(
    symbol: &str,
    name: &str,
    currency: &str,
    price: f64,
    chg: f64,
    pct: f64,
    hi: f64,
    lo: f64,
    vol: u64,
    market_cap: u64,
) -> ConstituentStock {
    let shares = if price > 0.0 {
        ((market_cap as f64) / price).round() as u64
    } else {
        0
    };
    ConstituentStock {
        symbol: symbol.to_string(),
        name: name.to_string(),
        currency: currency.to_string(),
        current_price: price,
        change: chg,
        change_percent: pct,
        day_high: hi,
        day_low: lo,
        volume: vol,
        market_cap,
        shares_outstanding: shares,
    }
}

