#[allow(clippy::too_many_arguments)]
fn stock(
    symbol: &str,
    name: &str,
    currency: &str,
    price: f64,
    chg: f64,
    pct: f64,
    hi: f64,
    lo: f64,
    vol: u64,
    market_cap: u64,
) -> ConstituentStock {
    ConstituentStock {
        symbol: symbol.to_string(),
        name: name.to_string(),
        currency: currency.to_string(),
        current_price: price,
        change: chg,
        change_percent: pct,
        day_high: hi,
        day_low: lo,
        volume: vol,
        market_cap,
    }
}

