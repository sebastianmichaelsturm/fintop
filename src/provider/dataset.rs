#[allow(clippy::too_many_arguments)]
fn currency(
    symbol: &str,
    display: &str,
    name: &str,
    rate: f64,
    chg: f64,
    pct: f64,
    hi: f64,
    lo: f64,
    base: &str,
    quote: &str,
) -> CurrencyQuote {
    CurrencyQuote {
        symbol: symbol.to_string(),
        display_symbol: display.to_string(),
        name: name.to_string(),
        rate,
        change: chg,
        change_percent: pct,
        day_high: hi,
        day_low: lo,
        base_currency: base.to_string(),
        quote_currency: quote.to_string(),
    }
}

